class ReferralPolicy(models.Model):
    """
    System-wide referral policy (singleton). Editable only by Super Admin.
    Policy changes apply only to newly created referral links.
    Existing links remain immutable.
    """
    default_expiry_days = models.PositiveIntegerField(
        default=30,
        validators=[MinValueValidator(1), MaxValueValidator(365)],
        verbose_name='Default Expiry (Days)',
        help_text='Default validity in days for new referral links when not overridden.'
    )
    allowed_max_use_tiers = models.JSONField(
        default=list,
        verbose_name='Allowed Max Use Tiers',
        help_text='List of allowed max_uses values (e.g. [3, 5, 10]). Admin Pandits select from these.'
    )
    max_allowed_expiry_days = models.PositiveIntegerField(
        default=90,
        validators=[MinValueValidator(1), MaxValueValidator(365)],
        verbose_name='Max Allowed Expiry (Days)',
        help_text='Maximum expiry days an Admin Pandit can select for a new link.'
    )
    max_allowed_uses = models.PositiveIntegerField(
        default=100,
        validators=[MinValueValidator(1), MaxValueValidator(100)],
        verbose_name='Max Allowed Uses (Cap)',
        help_text='Upper cap for max_uses (validates against ReferralLink validator).'
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'referrals_referral_policy'
        verbose_name = 'Referral Policy'
        verbose_name_plural = 'Referral Policies'

    def save(self, *args, **kwargs):
        self.pk = 1
        super().save(*args, **kwargs)

    @classmethod
    def load(cls):
        obj, _ = cls.objects.get_or_create(
            pk=1,
            defaults={
                'default_expiry_days': 30,
                'allowed_max_use_tiers': [5, 10, 50, 100],
                'max_allowed_expiry_days': 90,
                'max_allowed_uses': 100,
            }
        )
        return obj
