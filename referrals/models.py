"""
Referral data models for Nitya Dharma platform.

This module defines models for referral links and usage tracking.
These models support the referral-based Pandit onboarding system.

Models:
- ReferralLink: Represents a referral link generated by Admin Pandit or Super Admin
- ReferralUsage: Tracks each usage of a referral link for audit purposes
- ReferralCustodian: Tracks custodianship when original referrer is deactivated
"""

from django.db import models
from django.core.exceptions import ValidationError
from django.core.validators import MinValueValidator, MaxValueValidator
from django.utils import timezone
from django.contrib.auth import get_user_model
from core.audit import log_blocked_deletion

User = get_user_model()


class ReferralLink(models.Model):
    """
    Represents a referral link generated by an Admin Pandit or Super Admin.
    
    Each referral link has:
    - A unique token (used in URL)
    - A hexadecimal referral code (must match token)
    - Maximum 5 uses
    - Automatic expiry when usage limit reached
    
    This model supports:
    - Limited-use referral links (max 5 uses)
    - Audit trail of referral generation
    - Usage tracking
    - Expiry management
    """
    
    # Creator: Only Admin Pandit or Super Admin can create referral links
    created_by = models.ForeignKey(
        User,
        on_delete=models.PROTECT,  # Never delete referral data (audit requirement)
        related_name='created_referral_links',
        verbose_name='Created By',
        help_text='Admin Pandit or Super Admin who generated this referral link'
    )
    
    # Referral code: 8-12 character alphanumeric code (A-Z, 0-9)
    # Format: REF-AP-XXXXXX (example: REF-AP-9XK2M7)
    # Security: Non-sequential, non-guessable
    code = models.CharField(
        max_length=12,
        unique=True,
        null=True,  # Nullable initially for existing records
        blank=True,
        db_index=True,
        verbose_name='Referral Code',
        help_text='Unique referral code (8-12 chars, A-Z, 0-9). Format: REF-AP-XXXXXX'
    )
    
    # Legacy fields (kept for backward compatibility during migration)
    # TODO: Remove after migration to code-only format
    token = models.CharField(
        max_length=64,
        unique=True,
        null=True,
        blank=True,
        db_index=True,
        verbose_name='Referral Token (Legacy)',
        help_text='Legacy token field - use code instead'
    )
    
    referral_code = models.CharField(
        max_length=64,
        unique=True,
        null=True,
        blank=True,
        db_index=True,
        verbose_name='Referral Code (Legacy)',
        help_text='Legacy referral code field - use code instead'
    )
    
    # Usage limits
    max_uses = models.PositiveIntegerField(
        default=5,
        validators=[MinValueValidator(1), MaxValueValidator(100)],
        verbose_name='Maximum Uses',
        help_text='Maximum number of times this referral link can be used (default: 5)'
    )
    
    used_count = models.PositiveIntegerField(
        default=0,
        verbose_name='Used Count',
        help_text='Number of times this referral link has been used'
    )
    
    # Active status
    is_active = models.BooleanField(
        default=True,
        verbose_name='Is Active',
        help_text='Whether this referral link is active. Automatically set to False when usage limit is reached.'
    )
    
    # Timestamps
    created_at = models.DateTimeField(
        auto_now_add=True,
        verbose_name='Created At',
        help_text='When this referral link was generated'
    )
    
    updated_at = models.DateTimeField(
        auto_now=True,
        verbose_name='Updated At',
        help_text='When this referral link was last updated'
    )
    
    # Expiry date (REQUIRED - TASK 1: Referral Model with Expiry)
    expires_at = models.DateTimeField(
        null=False,
        blank=False,
        db_index=True,
        verbose_name='Expires At',
        help_text='Expiry date for this referral link (required). Referral auto-expires when expires_at < now()'
    )
    
    # Status field (TASK 1: Status tracking)
    STATUS_ACTIVE = 'active'
    STATUS_EXPIRED = 'expired'
    STATUS_REVOKED = 'revoked'
    
    STATUS_CHOICES = [
        (STATUS_ACTIVE, 'Active'),
        (STATUS_EXPIRED, 'Expired'),
        (STATUS_REVOKED, 'Revoked'),
    ]
    
    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default=STATUS_ACTIVE,
        db_index=True,
        verbose_name='Status',
        help_text='Referral status: active, expired, or revoked'
    )
    
    # Audit snapshot fields (Task 3.6 - Referral Audit Enrichment)
    # These fields store immutable snapshots of referrer state at creation time
    # They are NEVER updated after creation to preserve historical truth
    
    # Referrer status at creation (snapshot)
    referrer_status_at_creation = models.CharField(
        max_length=20,
        null=True,
        blank=True,
        choices=[
            ('pending', 'Pending'),
            ('active', 'Active'),
            ('rejected', 'Rejected'),
        ],
        verbose_name='Referrer Status at Creation',
        help_text='Immutable snapshot of referrer status when this referral link was created. Never updated after creation.'
    )
    
    # Referrer block state at creation (snapshot)
    # Note: Block states will be implemented in Module 11 (Admin Governance)
    # For now, we use 'none' as default, and this field will be populated when blocking is implemented
    referrer_block_state_at_creation = models.CharField(
        max_length=20,
        null=True,
        blank=True,
        choices=[
            ('none', 'None'),
            ('limited_blocked', 'Limited Blocked'),
            ('fully_blocked', 'Fully Blocked'),
        ],
        default='none',
        verbose_name='Referrer Block State at Creation',
        help_text='Immutable snapshot of referrer block state when this referral link was created. Never updated after creation.'
    )
    
    class Meta:
        verbose_name = 'Referral Link'
        verbose_name_plural = 'Referral Links'
        db_table = 'referrals_referral_link'
        ordering = ['-created_at']
        indexes = [
            models.Index(fields=['token']),
            models.Index(fields=['referral_code']),
            models.Index(fields=['created_by', 'is_active']),
            models.Index(fields=['expires_at']),  # TASK 1: Index for expiry queries
            models.Index(fields=['status']),  # TASK 1: Index for status queries
        ]
    
    def __str__(self):
        return f"Referral Link {self.token[:8]}... (by {self.created_by.email})"
    
    def is_expired(self):
        """
        Check if referral link is expired (TASK 1: Expiry enforcement).
        
        Returns True if:
        - status = expired or revoked
        - used_count >= max_uses
        - OR is_active = False
        - OR expires_at has passed
        """
        if self.status in [self.STATUS_EXPIRED, self.STATUS_REVOKED]:
            return True
        if self.used_count >= self.max_uses:
            return True
        if not self.is_active:
            return True
        if self.expires_at and self.expires_at < timezone.now():
            return True
        return False
    
    def is_valid(self):
        """
        Helper method to check if referral is valid (TASK 1: Helper method).
        
        Returns True if:
        - status = active
        - is_active = True
        - used_count < max_uses
        - expires_at is in the future
        """
        if self.status != self.STATUS_ACTIVE:
            return False
        if not self.is_active:
            return False
        if self.used_count >= self.max_uses:
            return False
        if self.expires_at < timezone.now():
            return False
        return True
    
    def can_be_used(self):
        """
        Check if referral link can be used for new registration.
        
        Alias for is_valid() for backward compatibility.
        """
        return self.is_valid()
    
    def delete(self, using=None, keep_parents=False):
        """
        Override delete() to prevent hard deletion.
        
        ReferralLinks must never be hard-deleted. Use status='revoked' or is_active=False.
        """
        log_blocked_deletion(self, actor=None, reason="ReferralLink hard deletion blocked - use status='revoked' instead")
        raise ValidationError(
            f"Hard deletion is not allowed for ReferralLink. "
            f"Use status='revoked' or is_active=False to deactivate the link. "
            f"Referral data must be preserved for audit purposes."
        )


class ReferralUsage(models.Model):
    """
    Tracks each usage of a referral link.
    
    This model provides:
    - Complete audit trail of referral usage
    - Abuse prevention (track who used which link)
    - Trust verification (verify referral chain)
    
    Each time a Pandit registers using a referral link, a ReferralUsage record is created.
    """
    
    # Referral link that was used
    referral_link = models.ForeignKey(
        ReferralLink,
        on_delete=models.PROTECT,  # Never delete referral data (audit requirement)
        related_name='usages',
        verbose_name='Referral Link',
        help_text='The referral link that was used'
    )
    
    # Pandit who registered using this referral link
    referred_pandit = models.ForeignKey(
        User,
        on_delete=models.PROTECT,  # Never delete referral data (audit requirement)
        related_name='referral_usages',
        verbose_name='Referred Pandit',
        help_text='The Pandit who registered using this referral link'
    )
    
    # Timestamp
    used_at = models.DateTimeField(
        auto_now_add=True,
        verbose_name='Used At',
        help_text='When this referral link was used for registration'
    )
    
    class Meta:
        verbose_name = 'Referral Usage'
        verbose_name_plural = 'Referral Usages'
        db_table = 'referrals_referral_usage'
        ordering = ['-used_at']
        # Ensure one Pandit can only use one referral link once
        unique_together = [['referral_link', 'referred_pandit']]
        indexes = [
            models.Index(fields=['referral_link', 'used_at']),
            models.Index(fields=['referred_pandit']),
        ]
    
    def delete(self, using=None, keep_parents=False):
        """
        Override delete() to prevent hard deletion.
        
        ReferralUsage records are append-only and must never be deleted.
        """
        log_blocked_deletion(self, actor=None, reason="ReferralUsage hard deletion blocked - records are append-only")
        raise ValidationError(
            f"Hard deletion is not allowed for ReferralUsage. "
            f"Usage records are append-only and immutable for audit purposes."
        )
    
    def __str__(self):
        return f"{self.referred_pandit.email} used referral {self.referral_link.token[:8]}... at {self.used_at}"

