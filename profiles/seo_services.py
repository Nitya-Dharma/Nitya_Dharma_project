"""
SEO metadata auto-generation services for PanditProfile.

Generates SEO title, description, and keywords from profile data.
"""
from django.utils.html import strip_tags


def generate_pandit_seo_title(profile):
    """
    Generate SEO title for Pandit Profile.
    
    Format: {Pandit Name} – {Primary Pooja} Pandit in {City}
    Uses only real data - no generic placeholders.
    
    Args:
        profile: PanditProfile instance
        
    Returns:
        str: SEO title (max 60 chars)
    """
    name = profile.get_display_name()
    
    # Get primary pooja (first pooja) - only if exists
    poojas = list(profile.poojas_performed.all()[:1])
    primary_pooja = poojas[0].name if poojas else None
    
    # Get city - only if exists
    cities = list(profile.cities_served.all()[:1])
    city = cities[0].name if cities else None
    
    # Build title using only available data
    parts = [name]
    
    if primary_pooja:
        parts.append(f"{primary_pooja} Pandit")
    else:
        parts.append("Pandit")
    
    if city:
        parts.append(f"in {city}")
    
    title = " – ".join(parts)
    
    # Truncate to 60 chars
    if len(title) > 60:
        title = title[:57] + "..."
    
    return title


def generate_pandit_seo_description(profile):
    """
    Generate SEO description for Pandit Profile.
    
    Uses only real data - no generic placeholders.
    Builds description conditionally based on available data.
    
    Args:
        profile: PanditProfile instance
        
    Returns:
        str: SEO description (max 160 chars)
    """
    name = profile.get_display_name()
    
    # Get city - only if exists
    cities = list(profile.cities_served.all()[:1])
    city = cities[0].name if cities else None
    
    # Get top 2-3 poojas - only if exists
    poojas = list(profile.poojas_performed.all()[:3])
    pooja_names = [p.name for p in poojas]
    
    # Get languages - only if exists
    languages = list(profile.languages.all()[:3])
    language_names = [l.name for l in languages]
    
    # Build description parts conditionally
    parts = []
    
    # Start with name and role
    if city:
        parts.append(f"{name} is a Hindu Pandit in {city}")
    else:
        parts.append(f"{name} is a Hindu Pandit")
    
    # Add poojas if available
    if pooja_names:
        if len(pooja_names) == 1:
            poojas_text = pooja_names[0]
        elif len(pooja_names) == 2:
            poojas_text = f"{pooja_names[0]} and {pooja_names[1]}"
        else:
            poojas_text = f"{', '.join(pooja_names[:-1])}, and {pooja_names[-1]}"
        parts.append(f"offering poojas such as {poojas_text}")
    
    # Add languages if available
    if language_names:
        if len(language_names) == 1:
            languages_text = language_names[0]
        elif len(language_names) == 2:
            languages_text = f"{language_names[0]} and {language_names[1]}"
        else:
            languages_text = f"{', '.join(language_names[:-1])}, and {language_names[-1]}"
        parts.append(f"Languages spoken: {languages_text}")
    
    # Join parts with periods, add final period
    description = ". ".join(parts) + "."
    
    # Truncate to 160 chars
    if len(description) > 160:
        description = description[:157] + "..."
    
    return description


def generate_pandit_seo_keywords(profile):
    """
    Generate SEO keywords for Pandit Profile.
    
    Uses only real data from profile - no generic placeholders.
    
    Args:
        profile: PanditProfile instance
        
    Returns:
        str: SEO keywords (comma-separated, unlimited length)
    """
    keywords = []
    
    # Add Pandit name
    name = profile.get_display_name()
    if name:
        keywords.append(name)
    
    # Get city - only if exists
    cities = list(profile.cities_served.all()[:1])
    if cities:
        keywords.append(f"Pandit in {cities[0].name}")
    
    # Get poojas - only real poojas
    poojas = list(profile.poojas_performed.all()[:5])
    for pooja in poojas:
        keywords.append(pooja.name)
    
    # Add standard keywords (these are acceptable as they're category descriptors)
    keywords.extend(["Hindu Pandit", "Vedic Pooja", "Religious Services"])
    
    # Get languages - only real languages
    languages = list(profile.languages.all()[:3])
    for lang in languages:
        keywords.append(f"{lang.name} Pandit")
    
    # Remove duplicates and join
    unique_keywords = list(dict.fromkeys(keywords))  # Preserves order
    return ", ".join(unique_keywords)


def auto_generate_pandit_seo(profile, force=False):
    """
    Auto-generate SEO metadata for Pandit Profile.
    
    Only generates if seo_autogenerated is True or force=True.
    
    Args:
        profile: PanditProfile instance
        force: If True, regenerate even if manually edited
        
    Returns:
        bool: True if SEO was generated
    """
    if not force and not profile.seo_autogenerated:
        return False
    
    profile.seo_title = generate_pandit_seo_title(profile)
    profile.seo_description = generate_pandit_seo_description(profile)
    profile.seo_keywords = generate_pandit_seo_keywords(profile)
    profile.seo_autogenerated = True
    
    return True

