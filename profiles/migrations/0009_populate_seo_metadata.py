def generate_seo_keywords(profile):
    """Generate SEO keywords for Pandit Profile."""
    keywords = []
    
    # Get city
    cities = list(profile.cities_served.all()[:1])
    if cities:
        keywords.append(f"Pandit in {cities[0].name}")
    
    # Get poojas
    poojas = list(profile.poojas_performed.all()[:5])
    for pooja in poojas:
        keywords.append(pooja.name)
    
    # Add standard keywords
    keywords.extend(["Hindu Pandit", "Vedic Pooja", "Religious Services"])
    
    # Get languages
    languages = list(profile.languages.all()[:3])
    for lang in languages:
        keywords.append(f"{lang.name} Pandit")
    
    # Remove duplicates and join
    unique_keywords = list(dict.fromkeys(keywords))  # Preserves order
    return ", ".join(unique_keywords)


def populate_seo_metadata(apps, schema_editor):
    """
    Populate SEO metadata for all existing PanditProfile instances.
    """
    PanditProfile = apps.get_model('profiles', 'PanditProfile')
    User = apps.get_model('accounts', 'User')
    
    # Get all profiles with related data
    # Note: cities_served is ManyToMany, so use prefetch_related, not select_related
    profiles = PanditProfile.objects.select_related('user').prefetch_related(
        'poojas_performed', 'cities_served', 'languages'
    ).all()
    
    updated_count = 0
    for profile in profiles:
        try:
            # Generate SEO metadata
            seo_title = generate_seo_title(profile)
            seo_description = generate_seo_description(profile)
            seo_keywords = generate_seo_keywords(profile)
            
            # Update profile
            PanditProfile.objects.filter(pk=profile.pk).update(
                seo_title=seo_title,
                seo_description=seo_description,
                seo_keywords=seo_keywords,
                seo_autogenerated=True,
            )
            updated_count += 1
        except Exception as e:
            # Skip profiles with errors, but continue processing others
            print(f"WARNING: Error updating profile {profile.pk}: {e}")
            continue
    
    print(f"Updated SEO metadata for {updated_count} Pandit Profile(s)")


