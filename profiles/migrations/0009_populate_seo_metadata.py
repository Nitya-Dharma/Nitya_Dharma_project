def generate_seo_title(profile):
    """Generate SEO title for Pandit Profile."""
    # Get display name (fallback logic)
    if profile.display_name:
        name = profile.display_name
    elif profile.user.first_name or profile.user.last_name:
        name = f"{profile.user.first_name} {profile.user.last_name}".strip()
    else:
        name = profile.user.email
    
    # Get primary pooja (first pooja)
    poojas = list(profile.poojas_performed.all()[:1])
    primary_pooja = poojas[0].name if poojas else "Pandit"
    
    # Get city
    cities = list(profile.cities_served.all()[:1])
    city = cities[0].name if cities else ""
    
    # Build title
    if city:
        title = f"{name} – {primary_pooja} Pandit in {city}"
    else:
        title = f"{name} – {primary_pooja} Pandit"
    
    # Truncate to 60 chars
    if len(title) > 60:
        title = title[:57] + "..."
    
    return title


