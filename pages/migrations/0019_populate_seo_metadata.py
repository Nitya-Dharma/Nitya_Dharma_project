def generate_seo_title(page):
    """Generate SEO title for Page."""
    page_name = page.title
    
    # Get city
    city = page.city.name if page.city else ""
    
    # Build title
    if city:
        title = f"{page_name} – {city}"
    else:
        title = page_name
    
    # Truncate to 60 chars
    if len(title) > 60:
        title = title[:57] + "..."
    
    return title


def generate_seo_description(page):
    """Generate SEO description for Page."""
    page_name = page.title
    
    # Get city
    city = page.city.name if page.city else "your area"
    
    # Get page type display
    page_type_choices = {
        'TEMPLE': 'temple',
        'BRAND': 'brand page',
        'TRUST': 'trust page',
        'SOCIAL_SERVICE': 'social service page',
    }
    page_type_display = page_type_choices.get(page.page_type, 'page')
    
    # Build description
    description = f"Explore {page_name} located in {city}. View details, updates, and information published on this {page_type_display}."
    
    # Truncate to 160 chars
    if len(description) > 160:
        description = description[:157] + "..."
    
    return description


