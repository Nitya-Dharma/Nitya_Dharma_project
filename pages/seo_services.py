"""
SEO metadata auto-generation services for Page.

Generates SEO title, description, and keywords from page data.
"""
from django.utils.html import strip_tags


def generate_page_seo_title(page):
    """
    Generate SEO title for Page.
    
    Format: {Page Name} – {City}
    
    Args:
        page: Page instance
        
    Returns:
        str: SEO title (max 60 chars)
    """
    page_name = page.title
    
    # Get city
    city = page.city.name if page.city else ""
    
    # Build title
    if city:
        title = f"{page_name} – {city}"
    else:
        title = page_name
    
    # Truncate to 60 chars
    if len(title) > 60:
        title = title[:57] + "..."
    
    return title


def generate_page_seo_description(page):
    """
    Generate SEO description for Page.
    
    Format: Explore {Page Name} located in {City}. View details, updates, and information published on this page.
    
    Args:
        page: Page instance
        
    Returns:
        str: SEO description (max 160 chars)
    """
    page_name = page.title
    
    # Get city
    city = page.city.name if page.city else "your area"
    
    # Get page type display
    page_type_display = page.get_page_type_display()
    
    # Build description
    description = f"Explore {page_name} located in {city}. View details, updates, and information published on this {page_type_display.lower()}."
    
    # Truncate to 160 chars
    if len(description) > 160:
        description = description[:157] + "..."
    
    return description


def generate_page_seo_keywords(page):
    """
    Generate SEO keywords for Page.
    
    Format: {Page Name}, {City}, Hindu Temple, Religious Page, {Custom keywords}
    
    Args:
        page: Page instance
        
    Returns:
        str: SEO keywords (comma-separated, unlimited length)
    """
    keywords = []
    
    # Add page name
    keywords.append(page.title)
    
    # Get city
    if page.city:
        keywords.append(page.city.name)
        keywords.append(f"Hindu Temple in {page.city.name}")
    
    # Get area
    if page.area:
        keywords.append(page.area.name)
    
    # Add page type specific keywords
    page_type_display = page.get_page_type_display()
    keywords.append(page_type_display)
    
    # Add standard keywords
    keywords.extend(["Hindu Temple", "Religious Page", "Spiritual Services"])
    
    # Remove duplicates and join
    unique_keywords = list(dict.fromkeys(keywords))  # Preserves order
    return ", ".join(unique_keywords)


def auto_generate_page_seo(page, force=False):
    """
    Auto-generate SEO metadata for Page.
    
    Only generates if seo_autogenerated is True or force=True.
    
    Args:
        page: Page instance
        force: If True, regenerate even if manually edited
        
    Returns:
        bool: True if SEO was generated
    """
    if not force and not page.seo_autogenerated:
        return False
    
    page.seo_title = generate_page_seo_title(page)
    page.seo_description = generate_page_seo_description(page)
    page.seo_keywords = generate_page_seo_keywords(page)
    page.seo_autogenerated = True
    
    return True

